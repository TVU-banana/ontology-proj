from typing import ContextManager, Protocol

from ontology_proj.application.ports.file_store import FileStore


class LocalProcessingStore(FileStore, Protocol):
    def exclusive(self) -> ContextManager: ...
    def source_path(self, document_id: str) -> str: ...
    def page_rotations(self, document_id: str) -> dict[int, int]: ...
    def read_published(self, document_id: str) -> dict | None: ...
    def read_artifact(self, document_id: str, artifact: str) -> dict: ...
    def save_artifact(self, document_id: str, artifact: str, value: dict) -> None: ...
    def publish(self, document_id: str, operation_id: str, configuration: dict, versions: dict) -> dict: ...
    def save_operation_artifact(self, operation_id: str, artifact: str, value: dict) -> None: ...
    def save_operation(self, value: dict) -> None: ...
    def list_operations(self) -> list[dict]: ...
    def read_operation(self, operation_id: str) -> dict: ...
