"""Answer ports; no SDK or persistence knowledge in the core."""
from typing import Protocol

class AnswerGenerator(Protocol):
    def request(self, question: str, context: dict) -> dict: ...
    def generate(self, request: dict) -> dict: ...

class AnswerJournal(Protocol):
    def save(self, question_id: str, phase: str, value: dict) -> None: ...

class EvidenceReader(Protocol):
    def read(self, evidence_id: str) -> dict: ...
