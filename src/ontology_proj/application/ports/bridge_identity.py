from typing import Protocol


class BridgeDirectory(Protocol):
    """Local authoritative bridge registration and source-bound ownership."""
    def adopt_existing(self, record: dict, source_kind: str) -> dict: ...
    def list(self) -> list[dict]: ...
    def register(self, value: dict) -> dict: ...
    def status(self, document: dict) -> dict: ...
    def binding(self, document: dict) -> dict: ...
    def resolve(self, document: dict, selected: str | None = None, confirm_details: bool = False) -> dict: ...
