from typing import Protocol, ContextManager


class FactExtractor(Protocol):
    def configuration(self) -> dict: ...
    def request(self, document: dict) -> dict: ...
    def extract(self, request: dict) -> dict: ...


class BusinessValidator(Protocol):
    def validate(self, candidate: dict, document: dict) -> dict: ...
    def validate_records(self, records: dict, document: dict) -> list[dict]: ...


class BusinessStore(Protocol):
    def exclusive(self) -> ContextManager: ...
    def read_artifact(self, document_id: str, artifact: str) -> dict: ...
    def read_business(self, document_id: str) -> dict | None: ...
    def read_business_artifact(self, document_id: str, name: str) -> dict: ...
    def begin_business(self, document_id: str, configuration: dict, fresh: bool) -> dict: ...
    def save_business(self, document_id: str, run_id: str, name: str, value: dict) -> None: ...
    def publish_business(self, document_id: str, run_id: str) -> dict: ...
