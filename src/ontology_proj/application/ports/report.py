"""Report persistence and validation boundaries; no provider or filesystem I/O."""
from typing import Protocol

class ReportRepository(Protocol):
    def create(self, report_id: str, operation_id: str, request: dict) -> None: ...
    def get(self, report_id: str) -> dict: ...
    def advance(self, report_id: str) -> None: ...
    def fail(self, report_id: str, code: str) -> None: ...
    def recover(self) -> None: ...
    def documents(self, scope: dict) -> list[dict]: ...
    def statements(self, scope: dict, document_ids: list[str]) -> list[str]: ...
    def commit(self, report: dict, snapshots: list[dict], manifest: dict) -> None: ...

class ReportStore(Protocol):
    def save_input(self, report_id: str, request: dict) -> None: ...
    def save(self, report: dict, markdown: str) -> dict: ...
    def read(self, report_id: str) -> tuple[dict, str, dict]: ...
    def validate(self, report: dict) -> None: ...
