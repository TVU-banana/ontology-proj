"""Plain ports for published-source indexing and retrieval."""
from typing import Protocol


class EmbeddingProvider(Protocol):
    def embed(self, texts: list[str], *, query: bool = False) -> list[list[float]]: ...


class PublishedInput(Protocol):
    def read(self, document_id: str) -> tuple[dict, dict]: ...


class SemanticRepository(Protocol):
    def begin(self, document_id: str, profile: str, retry: bool) -> dict: ...
    def publish(self, document_id: str, run_id: str, profile: str, chunks: list[dict], excluded: list[dict]) -> None: ...
    def fail(self, document_id: str, run_id: str, code: str) -> None: ...
    def allowed_documents(self, scope: dict) -> list[dict]: ...
    def search(self, vector: list[float], profile: str, pool_limit: int) -> list[dict]: ...

