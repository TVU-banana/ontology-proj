"""Graph persistence boundary; SDK and Cypher stay in adapters."""
from typing import Protocol


class GraphRepository(Protocol):
    def initialize(self) -> None: ...
    def replay(self, request: dict) -> dict | None: ...
    def register(self, source: dict, request: dict) -> dict: ...
    def request_processing(self, document_id: str, request: dict, configuration: str, retry: bool) -> dict: ...
    def document(self, document_id: str) -> dict: ...
    def operation(self, operation_id: str) -> dict: ...
    def advance(self, operation_id: str, stage: str, document_status: str) -> None: ...
    def commit_bundle(self, operation_id: str, document: dict, records: dict, artifacts: list[str]) -> dict: ...
    def fail(self, operation_id: str, code: str, artifacts: list[str], counts: dict | None = None) -> None: ...
    def recover(self) -> list[str]: ...
    def close(self) -> None: ...
